/**
 * Writes js/config/twist-table.js: for every campaign level, the twists it
 * plays with, the layout attempt that passed validation and the puzzle
 * length. Runs the full validation (lines under the rules, cells, combos,
 * puzzle solver) so the phone never has to.
 *
 *   npm run twists
 */
import { writeFileSync } from 'node:fs';
import { tableEntries } from './twist-plan.js';
import { TWIST_CODES } from '../js/config/twist-table.js';

const { table, stats } = tableEntries();
const rows = Object.entries(table).map(([n, e]) => `  ${n}: ${JSON.stringify(e).replace(/"/g, "'")},`);
const codes = Object.entries(TWIST_CODES).map(([c, id]) => `${c}: '${id}'`).join(', ');
const file = [
  '/**',
  ' * GENERATED by tools/gen-twist-table.js — do not edit by hand.',
  ' * Run `npm run twists` after changing the level table, the twist rules or',
  ' * the layout generator. The tests fail if this file is out of date.',
  ' *',
  ' * level: [twist codes, attempt that passed validation, puzzle moves]',
  ' */',
  `export const TWIST_CODES = { ${codes} };`,
  'export const TWIST_TABLE = {',
  ...rows,
  '};',
  '',
].join('\n');
writeFileSync(new URL('../js/config/twist-table.js', import.meta.url), file);
console.log('twist levels:', rows.length, JSON.stringify(stats));
